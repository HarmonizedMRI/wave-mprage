function [targetBlock, targetBlockIndex] = findAdcBlock(sequence, targetAdc)
    [~, nBlocks] = sequence.duration();
    adcCounter = 0;
    for blockIndex = 1:nBlocks
        block = sequence.getBlock(blockIndex);
        if ~isempty(block.adc)
            adcCounter = adcCounter+1;
            if adcCounter == targetAdc
                targetBlock = block;
                targetBlockIndex = blockIndex;
                return;
            end
        end
    end
    error('Requested ADC block was not decoded.');
end

function slewPeak = arbitrarySlewPeak(waveform, first, last, dt)
    waveform = waveform(:);
    slew = [2*(first-waveform(1)); ...
        waveform(2:end)-waveform(1:end-1); ...
        2*(waveform(end)-last)]/dt;
    slewPeak = max(abs(slew));
end

function slewPeak = gradientEventSlewPeak(gradient, dt)
    if strcmp(gradient.type, 'trap')
        rampTimes = [gradient.riseTime gradient.fallTime];
        rampTimes = rampTimes(rampTimes > 0);
        slewPeak = max(abs(gradient.amplitude)./rampTimes);
    elseif abs(gradient.tt(1)) <= dt/10
        slewPeak = max(abs(diff(gradient.waveform)./diff(gradient.tt)));
    else
        slewPeak = arbitrarySlewPeak( ...
            gradient.waveform, gradient.first, gradient.last, dt);
    end
end

function area = integrateCellCenteredToTime(gradient, endTime)
    dt = median(diff(gradient.tt));
    relativeEnd = endTime-gradient.delay;
    nWholeCells = floor(relativeEnd/dt+1e-9);
    remainder = relativeEnd-nWholeCells*dt;
    area = sum(gradient.waveform(1:nWholeCells))*dt;
    if remainder > dt/10
        area = area+gradient.waveform(nWholeCells+1)*remainder;
    end
end

function block = normalizeDecodedBlock(block)
    if isfield(block, 'label')
        block = rmfield(block, 'label');
    end
    gradientFields = {'gx','gy','gz'};
    for ii = 1:numel(gradientFields)
        name = gradientFields{ii};
        if isstruct(block.(name))
            metadataFields = intersect(fieldnames(block.(name)), ...
                {'id','shape_id','time_id'});
            if ~isempty(metadataFields)
                block.(name) = rmfield(block.(name), metadataFields);
            end
        end
    end
end
