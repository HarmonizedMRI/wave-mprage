clear; clc

addpath('/Users/yiyund/Code_mgh/pulseq/matlab');

evaluationPath = fileparts(mfilename('fullpath'));
mpragePath = fullfile(evaluationPath, 'output', 'v1.5.1', ...
    'high_slew_wave_mprage');
referenceRoot = '/Users/yiyund/Code_mgh/sources/seq_for_eva';
calibrationPath = fullfile(referenceRoot, 'outputs', 'flash_calibration', ...
    'v1.5.1', 'high_slew');
cases = struct( ...
    'cycles', {10, 20, 25}, ...
    'amplitude', {12.732, 6.3662, 5.093}, ...
    'tag', {'12p732', '6p3662', '5p093'});
states = {'sinzero', 'sinctr'};

gammaHz = 42.576e6;
dt = 10e-6;
readoutDuration = 5e-3;
physicalSlew = 180;
lowPnsSlew = 63;
nImage = 16000;
nCalibration = 1312;
labelNames = {'LIN','PAR','ECO','AVG','SET','REF','IMA'};

for caseIndex = 1:numel(cases)
    waveCase = cases(caseIndex);
    stateResults = struct([]);

    for stateIndex = 1:numel(states)
        state = states{stateIndex};
        centered = strcmp(state, 'sinctr');
        mprageName = sprintf([ ...
            'mprage_wave_SAG_FOV200x240x250_ETL250_R1x3_os4_', ...
            'A%s_C%d_%s_skyra_v151.seq'], ...
            waveCase.tag, waveCase.cycles, state);
        calibrationName = sprintf([ ...
            'gre3d_flashcal_SAG_FOV200x240x250_N250_os4_', ...
            'A%s_C%d_%s_skyra_v151.seq'], ...
            waveCase.tag, waveCase.cycles, state);
        assert(strlength(string(mprageName)) <= 100, ...
            'Wave-MPRAGE filename exceeds 100 characters.');
        mprageFile = fullfile(mpragePath, mprageName);
        calibrationFile = fullfile(calibrationPath, calibrationName);
        assert(exist(mprageFile, 'file') == 2, ...
            'Missing Wave-MPRAGE sequence: %s', mprageFile);
        assert(exist(calibrationFile, 'file') == 2, ...
            'Missing standalone calibration: %s', calibrationFile);

        sequence = mr.Sequence();
        sequence.read(mprageFile);
        calibration = mr.Sequence();
        calibration.read(calibrationFile);
        [timingOk, timingErrors] = sequence.checkTiming;
        assert(timingOk, 'Reloaded timing failed for %s:\n%s', ...
            mprageFile, strjoin(timingErrors, newline));
        [calibrationTimingOk, calibrationTimingErrors] = ...
            calibration.checkTiming;
        assert(calibrationTimingOk, ...
            'Reloaded standalone timing failed for %s:\n%s', ...
            calibrationFile, strjoin(calibrationTimingErrors, newline));

        assert(sequence.getDefinition('MPRAGE_ETL_Target') == 250 && ...
            sequence.getDefinition('MPRAGE_ImageADCs') == nImage, ...
            'MPRAGE ETL or image ADC count changed.');
        assert(sequence.getDefinition('Calibration_RefscanADCs') == ...
            nCalibration, 'Calibration ADC count changed.');
        assert(sequence.getDefinition('CalibrationWaveCycles') == ...
            waveCase.cycles, 'Wave-cycle definition mismatch.');
        assert(abs(sequence.getDefinition( ...
            'CalibrationWaveAmplitude_mTm')-waveCase.amplitude) < 1e-12, ...
            'Wave-amplitude definition mismatch.');
        assert(sequence.getDefinition( ...
            'CalibrationWaveCenteredOnNowave') == centered && ...
            sequence.getDefinition('MPRAGE_WaveCenteredOnNowave') == centered, ...
            'Image/calibration sine-centering definitions disagree.');
        assert(sequence.getDefinition('ActiveWaveSlewLimit_Tms') == ...
            physicalSlew && ...
            sequence.getDefinition('WaveRampSlewLimit_Tms') == lowPnsSlew && ...
            sequence.getDefinition('NonWaveSlewLimit_Tms') == lowPnsSlew, ...
            'High-slew/low-PNS system definitions mismatch.');
        storedFov = sequence.getDefinition('FOV');
        assert(max(abs(storedFov(:).'-1e-3*[200 240 250])) < 1e-12 && ...
            isequal([sequence.getDefinition('Nx'), ...
            sequence.getDefinition('Ny'), sequence.getDefinition('Nz')], ...
            [200 240 250]), 'SAG FOV/matrix definitions changed.');
        assert(strcmp(sequence.getDefinition('ReadoutAxis'), 'z') && ...
            strcmp(sequence.getDefinition('InnerPEAxis'), 'x') && ...
            strcmp(sequence.getDefinition('OuterPEAxis'), 'y'), ...
            'SAG axis definitions changed.');

        labels = sequence.evalLabels('evolution', 'adc');
        calibrationLabels = calibration.evalLabels('evolution', 'adc');
        assert(numel(labels.LIN) == nImage+nCalibration, ...
            'Combined ADC count changed.');
        imageRange = 1:nImage;
        calibrationRange = nImage+(1:nCalibration);
        assert(all(labels.REF(imageRange) == 0) && ...
            all(labels.IMA(imageRange) == 0) && ...
            all(labels.SET(imageRange) == 0) && ...
            all(labels.ECO(imageRange) == 0) && ...
            all(labels.AVG(imageRange) == 0), ...
            'MPRAGE image routing changed.');
        assert(numel(unique(labels.PAR(imageRange))) == 200 && ...
            numel(unique(labels.LIN(imageRange))) == 80, ...
            'MPRAGE accelerated PE coverage changed.');
        imagePairs = [labels.PAR(imageRange).', labels.LIN(imageRange).'];
        assert(size(unique(imagePairs, 'rows'), 1) == nImage, ...
            'MPRAGE image labels contain duplicate PE pairs.');
        for labelIndex = 1:numel(labelNames)
            labelName = labelNames{labelIndex};
            integratedValues = labels.(labelName)(calibrationRange);
            assert(isequal(integratedValues(:), ...
                calibrationLabels.(labelName)(:)), ...
                'Calibration label mismatch for %s.', labelName);
        end

        assert(abs(sequence.getDefinition('Calibration_TE') - ...
            calibration.getDefinition('CalibrationTE')) < 1e-12 && ...
            abs(sequence.getDefinition('Calibration_TRinner') - ...
            calibration.getDefinition('CalibrationTR')) < 1e-12, ...
            'Integrated and standalone calibration TE/TR mismatch.');
        [duration, nBlocks] = sequence.duration();
        [calibrationDuration, calibrationBlocks] = calibration.duration();
        assert(calibrationBlocks == 6648, ...
            'Unexpected standalone calibration block count.');
        for offset = 0:calibrationBlocks-1
            integratedBlock = normalizeDecodedBlock( ...
                sequence.getBlock(nBlocks-offset));
            standaloneBlock = normalizeDecodedBlock( ...
                calibration.getBlock(calibrationBlocks-offset));
            assert(isequaln(integratedBlock, standaloneBlock), ...
                ['Integrated calibration physical block mismatch at ', ...
                'reverse offset %d.'], offset);
        end

        imageCenterAdc = find(labels.LIN(imageRange) == 120 & ...
            labels.PAR(imageRange) == 100, 1);
        assert(~isempty(imageCenterAdc), ...
            'MPRAGE image mask is missing physical k-space center.');
        [imageBlock, imageBlockIndex] = findAdcBlock(sequence, imageCenterAdc);
        assert(~isempty(imageBlock.gx) && ~isempty(imageBlock.gy) && ...
            ~isempty(imageBlock.gz), ...
            'Image ADC block is missing a physical wave/readout axis.');
        nPreCells = round(imageBlock.adc.delay/dt);
        g0 = gammaHz*waveCase.amplitude*1e-3;
        sinePreSlew = arbitrarySlewPeak( ...
            imageBlock.gy.waveform(1:nPreCells), 0, 0, dt)/gammaHz;
        cosinePreSlew = arbitrarySlewPeak( ...
            imageBlock.gx.waveform(1:nPreCells), 0, g0, dt)/gammaHz;
        sineActive = imageBlock.gy.waveform(nPreCells+1:end);
        cosineActive = imageBlock.gx.waveform(nPreCells+1:end);
        sineActiveSlew = arbitrarySlewPeak(sineActive, 0, 0, dt)/gammaHz;
        cosineActiveSlew = arbitrarySlewPeak( ...
            cosineActive, g0, g0, dt)/gammaHz;
        assert(max([sinePreSlew cosinePreSlew]) <= lowPnsSlew*1.001, ...
            'An image wave pre-ramp exceeds the low-PNS slew limit.');
        assert(max([sineActiveSlew cosineActiveSlew]) <= ...
            physicalSlew*1.001 && ...
            min([sineActiveSlew cosineActiveSlew]) > 150, ...
            'Image active-wave slew is outside the intended envelope.');
        sinePost = sequence.getBlock(imageBlockIndex+1).gy;
        cosinePost = sequence.getBlock(imageBlockIndex+1).gx;
        sinePostSlew = gradientEventSlewPeak(sinePost, dt)/gammaHz;
        cosinePostSlew = gradientEventSlewPeak(cosinePost, dt)/gammaHz;
        assert(max([sinePostSlew cosinePostSlew]) <= lowPnsSlew*1.001, ...
            'An image wave post event exceeds the low-PNS slew limit.');

        omega = 2*pi*waveCase.cycles/readoutDuration;
        idealRadius = g0/omega;
        if mod(waveCase.cycles, 2) == 0
            rawMoment = 0;
            effectiveRadius = idealRadius;
        else
            nRasterCells = round(readoutDuration/dt);
            rawMoment = g0*dt*cot(pi*waveCase.cycles/nRasterCells);
            effectiveRadius = rawMoment/2;
        end
        if centered
            expectedCenterMoment = rawMoment-effectiveRadius;
        else
            expectedCenterMoment = 0;
        end
        adcCenterTime = imageBlock.adc.delay + ...
            0.5*imageBlock.adc.numSamples*imageBlock.adc.dwell;
        centerMoment = integrateCellCenteredToTime( ...
            imageBlock.gy, adcCenterTime);
        assert(abs(centerMoment-expectedCenterMoment) < 5e-5, ...
            'Image sine center moment %.9g differs from %.9g 1/m.', ...
            centerMoment, expectedCenterMoment);

        stateResults(stateIndex).duration = duration;
        stateResults(stateIndex).blocks = nBlocks;
        stateResults(stateIndex).labels = labels;
        stateResults(stateIndex).sineActive = sineActive;
        stateResults(stateIndex).cosineWave = imageBlock.gx.waveform;
        stateResults(stateIndex).centerMoment = centerMoment;

        fprintf([ ...
            'C%d %-7s passed: image active sine/cos %.6f/%.6f, ', ...
            'pre %.6f/%.6f, post %.6f/%.6f T/m/s; ', ...
            'Gy center %+.9f 1/m; cal %.4f/%.4f ms; ', ...
            '%.6f s, %d blocks; tail=%d blocks exact.\n'], ...
            waveCase.cycles, state, sineActiveSlew, cosineActiveSlew, ...
            sinePreSlew, cosinePreSlew, sinePostSlew, cosinePostSlew, ...
            centerMoment, sequence.getDefinition('Calibration_TE')*1e3, ...
            sequence.getDefinition('Calibration_TRinner')*1e3, ...
            duration, nBlocks, calibrationBlocks);
        assert(calibrationDuration > 0, ...
            'Standalone calibration duration must be positive.');
    end

    assert(abs(stateResults(1).duration-stateResults(2).duration) < 1e-12 && ...
        stateResults(1).blocks == stateResults(2).blocks, ...
        'Sine centering changed Wave-MPRAGE duration or block count.');
    for labelIndex = 1:numel(labelNames)
        labelName = labelNames{labelIndex};
        assert(isequal(stateResults(1).labels.(labelName), ...
            stateResults(2).labels.(labelName)), ...
            'Sine centering changed combined %s labels.', labelName);
    end
    assert(max(abs(stateResults(1).sineActive - ...
        stateResults(2).sineActive)) < 1e-8, ...
        'Sine centering changed the image active sine samples.');
    assert(max(abs(stateResults(1).cosineWave - ...
        stateResults(2).cosineWave)) < 1e-8, ...
        'Sine centering changed the image cosine waveform.');
end

